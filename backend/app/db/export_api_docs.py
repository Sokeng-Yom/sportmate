"""
Exports the API contract for the frontend. From backend/:   python -m app.db.export_api_docs
Writes ../documentation/openapi.json, api-examples.json (mock responses) and API.md.
"""
import json
from pathlib import Path

from app.main import app

STRING_FORMATS = {
    "uuid": "3f2b8c1e-8a46-4d3e-9b5a-1c2d3e4f5a6b",
    "date": "2030-01-15",
    "time": "19:00:00",
    "date-time": "2030-01-15T19:00:00",
}
METHODS = {"get", "post", "put", "patch", "delete"}


def _resolve(schema: dict, spec: dict) -> dict:
    ref = schema.get("$ref")
    return spec["components"]["schemas"][ref.split("/")[-1]] if ref else schema


def example_for(schema: dict, spec: dict, depth: int = 0):
    """Builds a realistic example value from an OpenAPI schema."""
    if depth > 8:
        return None
    schema = _resolve(schema, spec)
    for key in ("anyOf", "oneOf"):
        if key in schema:
            options = [s for s in schema[key] if s.get("type") != "null"]
            return example_for(options[0], spec, depth + 1) if options else None
    if "allOf" in schema:
        merged: dict = {}
        for part in schema["allOf"]:
            value = example_for(part, spec, depth + 1)
            if isinstance(value, dict):
                merged.update(value)
        return merged
    if "enum" in schema:
        return schema["enum"][0]
    kind = schema.get("type")
    if kind == "object" or "properties" in schema:
        return {name: example_for(prop, spec, depth + 1) for name, prop in schema.get("properties", {}).items()}
    if kind == "array":
        return [example_for(schema.get("items", {}), spec, depth + 1)]
    if kind == "string":
        return STRING_FORMATS.get(schema.get("format"), "string")
    if kind == "integer":
        return 1
    if kind == "number":
        return 0.5
    if kind == "boolean":
        return True
    return None


def _type_name(schema: dict, spec: dict) -> str:
    schema = _resolve(schema, spec)
    if "anyOf" in schema:
        options = [s for s in schema["anyOf"] if s.get("type") != "null"]
        return _type_name(options[0], spec) if options else "any"
    return schema.get("format") or schema.get("type") or "any"


def build_examples(spec: dict) -> dict:
    examples = {}
    for path, methods in sorted(spec["paths"].items()):
        for method, operation in methods.items():
            if method.lower() not in METHODS:
                continue
            entry = {"summary": operation.get("summary", ""), "query": [], "request": None, "status": None, "response": None}
            for param in operation.get("parameters", []):
                if param.get("in") == "query":
                    entry["query"].append(
                        {"name": param["name"], "required": param.get("required", False),
                         "type": _type_name(param.get("schema", {}), spec)}
                    )
            body = operation.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
            if body:
                entry["request"] = example_for(body, spec)
            for code, response in operation.get("responses", {}).items():
                if code.startswith("2"):
                    entry["status"] = int(code)
                    schema = response.get("content", {}).get("application/json", {}).get("schema")
                    if schema:
                        entry["response"] = example_for(schema, spec)
                    break
            examples[f"{method.upper()} {path}"] = entry
    return examples


def render_markdown(examples: dict) -> str:
    lines = [
        "# SportMate API cheat sheet",
        "",
        "Generated by `python -m app.db.export_api_docs`. Do not edit by hand.",
        "",
        "Every endpoint needs `Authorization: Bearer <supabase access token>`. Errors are "
        '`{"detail": "message"}` with status 400, 401, 403, 404, 409, 422 or 429. '
        "Live chat delivery uses Supabase Realtime, not this API.",
        "",
        "| Endpoint | What it does | Query parameters (* = required) | Success |",
        "|---|---|---|---|",
    ]
    for key, entry in examples.items():
        query = ", ".join(f"{q['name']}{'*' if q['required'] else ''}" for q in entry["query"]) or "-"
        lines.append(f"| `{key}` | {entry['summary']} | {query} | {entry['status']} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    spec = app.openapi()
    out = Path("..") / "documentation"
    out.mkdir(exist_ok=True)
    examples = build_examples(spec)
    (out / "openapi.json").write_text(json.dumps(spec, indent=2), encoding="utf-8")
    (out / "api-examples.json").write_text(json.dumps(examples, indent=2), encoding="utf-8")
    (out / "API.md").write_text(render_markdown(examples), encoding="utf-8")
    print(f"Wrote {len(examples)} endpoints to {out.resolve()}")


if __name__ == "__main__":
    main()
